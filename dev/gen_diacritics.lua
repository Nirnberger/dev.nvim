-- Usage: nvim -l dev/gen_diacritics.lua <rowcolumn-diacritics.txt> > lua/inkmath/term/diacritics.lua
-- Source: https://sw.kovidgoyal.net/kitty/_downloads/f0a0de9ec8d9ff4456206db8e0814937/rowcolumn-diacritics.txt
local out = { "-- Generated by dev/gen_diacritics.lua from kitty's rowcolumn-diacritics.txt. Do not edit.", "return {" }
local row = "  "
for line in io.lines(arg[1]) do
  local hex = line:match("^(%x+);")
  if hex then
    local item = string.format("0x%04X,", tonumber(hex, 16))
    if #row + #item + 1 > 100 then
      out[#out + 1] = (row:gsub("%s+$", ""))
      row = "  "
    end
    row = row .. item .. " "
  end
end
out[#out + 1] = (row:gsub("%s+$", ""))
out[#out + 1] = "}"
io.write(table.concat(out, "\n"), "\n")
